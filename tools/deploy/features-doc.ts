/**
 * Writes the feature index `docs/features.md`: every editor, the comparison with iD and Rapid, and every package with
 * the first lines of its README. The same data as the overview page (`showcase/features.ts`, `apps/<app>/overview.json`,
 * the app configs), so the two never disagree. A test fails when the committed file is out of date.
 *
 *   bun run features-doc
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { appsOf, listedApp, readDeployEnv } from './build-pages.ts'
import { GROUPS } from './showcase/features.ts'
import { supportOf } from './showcase/page.ts'
import type { ListedApp, Support } from './showcase/types.ts'

const ROOT = join(import.meta.dir, '../..')
export const FEATURES_DOC = join(ROOT, 'docs', 'features.md')

const MARK: Record<Support, string> = { yes: '✓', partial: '◐', no: '–' }

/** The first paragraph of a README after its title, on one line */
export function readmeSummary(text: string) {
  const lines = text.split('\n')
  const start = lines.findIndex(
    (line, index) =>
      index > 0 && line.trim() !== '' && !line.startsWith('#') && !line.startsWith('**Status'),
  )
  if (start === -1) return ''
  const paragraph: string[] = []
  for (const line of lines.slice(start)) {
    if (line.trim() === '' || line.startsWith('#')) break
    paragraph.push(line.trim())
  }
  return paragraph.join(' ').replace(/\|/g, '\\|')
}

function packageRows(apps: ListedApp[]) {
  const dir = join(ROOT, 'packages')
  return readdirSync(dir)
    .filter((name) => existsSync(join(dir, name, 'package.json')))
    .sort()
    .map((name) => {
      const readme = join(dir, name, 'README.md')
      const summary = existsSync(readme)
        ? readmeSummary(readFileSync(readme, 'utf8'))
        : '(no README yet)'
      const source = existsSync(join(dir, name, 'src', 'index.ts'))
        ? readFileSync(join(dir, name, 'src', 'index.ts'), 'utf8')
        : ''
      const used = apps
        .filter((app) =>
          [...app.factories].some((factory) =>
            new RegExp(
              `export (function|const) ${factory}\\b|export \\{[^}]*\\b${factory}\\b`,
            ).test(source),
          ),
        )
        .map((app) => app.folder)
      const where = name.startsWith('module-')
        ? used.length > 0
          ? used.join(', ')
          : 'none'
        : 'shared'
      return `| [${name}](../packages/${name}/README.md) | ${summary} | ${where} |`
    })
}

export function featuresDoc(apps: ListedApp[]) {
  const appHeads = apps.map((app) => app.name.replace(/^Maid /, ''))
  const editors = apps.map(
    (app) =>
      `| **${app.name}** ([config](../apps/${app.folder}/src/maid.config.ts)) | ${app.overview.tagline}. ${app.overview.description} | ${[
        ...app.factories,
      ]
        .sort()
        .map((factory) => `\`${factory}\``)
        .join(' ')} |`,
  )
  const groups = GROUPS.map((group) => {
    const rows = group.rows.map((row) => {
      const docs = row.pkg ? ` ([docs](../packages/${row.pkg}/README.md))` : ''
      const note = row.note ? ` _${row.note}_` : ''
      const cells = [row.iD, row.rapid, ...apps.map((app) => supportOf(row, app))].map(
        (support) => MARK[support],
      )
      return `| **${row.title}**${docs}: ${row.text}${note} | ${cells.join(' | ')} |`
    })
    return [
      `### ${group.title}`,
      '',
      ...(group.intro ? [group.intro, ''] : []),
      `| Feature | iD | Rapid | ${appHeads.join(' | ')} |`,
      `| --- | --- | --- | ${appHeads.map(() => '---').join(' | ')} |`,
      ...rows,
      '',
    ].join('\n')
  })
  return `# What Maid has built

The index of Maid's features, editors and packages. Generated by \`bun run features-doc\` from
\`tools/deploy/showcase/features.ts\`, \`apps/<app>/overview.json\` and the app configs; edit those, not this file. The
same data makes the overview page of the deployed site (https://osm-editor-kit.github.io/maid/).

## Editors

| Editor | What it is for | Modules in its config |
| --- | --- | --- |
${editors.join('\n')}

## Features compared with iD and Rapid

✓ yes, ◐ partly, – no. iD is [openstreetmap/iD](https://github.com/openstreetmap/iD), Rapid is
[bhousel/Rapid](https://github.com/bhousel/Rapid), both checked in their code on their main branches (2026-11-12). A Maid
column follows the modules the app's config calls.

${groups.join('\n')}
## Packages

Every package in \`packages/\`, with the first paragraph of its README. Modules (\`module-*\`) are switched on per app,
with the apps that call them; the other packages are shared by the apps and modules that import them.

| Package | What it is | Apps |
| --- | --- | --- |
${packageRows(apps).join('\n')}
`
}

export function deployedApps() {
  const env = readDeployEnv(readFileSync(join(ROOT, 'deploy.env'), 'utf8'))
  return appsOf(env.MAID_APP ?? 'maid').map(listedApp)
}

if (import.meta.main) {
  writeFileSync(FEATURES_DOC, featuresDoc(deployedApps()))
  console.log(`Wrote ${FEATURES_DOC}`)
}

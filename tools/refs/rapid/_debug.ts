import { chromium } from '@playwright/test'
const browser = await chromium.launch({ channel: 'chrome', args: ['--host-resolver-rules=MAP * ~NOTFOUND, EXCLUDE localhost, EXCLUDE 127.0.0.1'] })
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } })
await context.route('**/*', (route) => (/^https?:\/\/(localhost|127\.0\.0\.1)[:/]/.test(route.request().url()) || /^(data|blob):/.test(route.request().url()) ? route.continue() : route.abort()))
const page = await context.newPage()
page.on('console', (m) => m.type() === 'error' && console.log('console.error', m.text().slice(0, 200)))
await page.goto(`http://localhost:8082/?scene=${process.argv[2] ?? 'small'}`)
await page.evaluate(() => window.__bench.ready())
const code = await Bun.file(process.argv[3]!).text()
console.log(JSON.stringify(await page.evaluate(code), null, 1))
await browser.close()
